/**
 * Write a ProsodyModel as src/speech/prosody-fitted.ts (pure data, so prosody.ts can import it).
 *   npx tsx scripts/speech/dump-prosody-model.ts <model.json|klatt> [note]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { KLATT_MODEL, type ProsodyModel } from '../../src/speech/prosody'

const [src = 'klatt', note = 'placeholder: Klatt rules and the hand-set tune'] = process.argv.slice(2)
const m = (src === 'klatt' ? { ...KLATT_MODEL, pitch: { accentSemitones: 4, declination: 1.2, finalFall: 4 } } : JSON.parse(readFileSync(src, 'utf8'))) as ProsodyModel & { pitch: Record<string, number> }
const r = (x: number) => Math.round(x * 1000) / 1000
const obj = (o: Record<string, number>) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${r(v)}`).join(', ')} }`
const table = Object.entries(m.durations).map(([k, [a, b]]) => `'${k}': [${Math.round(a)}, ${Math.round(b)}]`).join(', ')
writeFileSync('src/speech/prosody-fitted.ts', `/**
 * Prosody fitted to recorded speech (${note}).
 * Generated by scripts/speech/fit-prosody.ts; do not edit by hand. Used by voices with prosody: 'fitted'.
 */
import type { ProsodyModel } from './prosody'

export const FITTED_MODEL: ProsodyModel = {
  durations: { ${table} },
  rules: ${obj(m.rules)},
  tune: ${obj(m.tune)},
}

/** pitch settings fitted with the model (accent size, declination, final fall, in the voice's units) */
export const FITTED_PITCH = ${obj(m.pitch)}
`)
console.log('wrote src/speech/prosody-fitted.ts')
