"""
Recorded consonant noise for the Strudel voice: short turbulence and release snippets cut from the
CMU ARCTIC awb recordings, written as generated data for the instrument's worklet, which plays them
in place of synthetic noise. The voice itself (glottal source, vowels, transitions) stays synthetic.

    python3 scripts/speech/corpus/extract-consonant-noise.py <wavDir> <alignDir> <out.ts> [--ms 160] [--bits 8]

Fricatives (f v θ ð s z ʃ ʒ): the middle 60% of the longest training tokens (ids before
arctic_b0490), high-passed at 1 kHz for voiced ones (their voicing comes from our own source),
joined with 5 ms crossfades up to --ms per phone. Releases (p b t d k g): 25 ms from the release
(the largest rise of 1–8 kHz energy near the end of the aligned stop), the token closest to the
phone's median spectrum. All at 16 kHz, RMS-normalised, mu-law 8 bit, base64.

CMU ARCTIC: Copyright Carnegie Mellon University, free to use and modify with attribution.
"""
import base64, glob, json, os, sys
import numpy as np
import librosa
import scipy.signal as sg

SR = 16000
FRIC = 'f v θ ð s z ʃ ʒ'.split()
VOICED_FRIC = set('v ð z ʒ'.split())
STOPS = 'p b t d k g'.split()
SIBILANT = set('s z ʃ ʒ'.split())
VOWELS = set('iː ɪ e æ ʌ ɑː ɒ ɔː ʊ uː ɜː ə i eɪ aɪ ɔɪ əʊ aʊ ɪə eə ʊə'.split())


def mulaw(x):
    x = np.clip(x, -1, 1)
    y = np.sign(x) * np.log1p(255 * np.abs(x)) / np.log1p(255)
    return np.round((y + 1) * 127.5).astype(np.uint8)


def main():
    wav_dir, align_dir, out = sys.argv[1:4]
    ms = 160
    if '--ms' in sys.argv:
        ms = int(sys.argv[sys.argv.index('--ms') + 1])
    hpv = '--hp-all' not in sys.argv
    hp = sg.butter(4, 1000, 'hp', fs=SR, output='sos')
    hps = sg.butter(4, 2000, 'hp', fs=SR, output='sos')
    toks = {p: [] for p in FRIC + STOPS}
    for jf in sorted(glob.glob(os.path.join(align_dir, 'arctic_*.json'))):
        a = json.load(open(jf))
        if a['id'] >= 'arctic_b0490':
            continue
        ph = a['phones']
        y = None
        for k, p in enumerate(ph):
            if p['phone'] not in toks:
                continue
            d = p['end'] - p['start']
            if y is None:
                y, _ = librosa.load(os.path.join(wav_dir, a['id'] + '.wav'), sr=SR)
            if p['phone'] in FRIC and d > 0.06:
                x = y[int((p['start'] + 0.2 * d) * SR):int((p['end'] - 0.2 * d) * SR)]
                toks[p['phone']].append((d, x))
            elif p['phone'] in STOPS and k + 1 < len(ph) and ph[k + 1]['phone'] in VOWELS and d > 0.04:
                seg = y[int((p['end'] - 0.035) * SR):int((p['end'] + 0.03) * SR)]
                if len(seg) < 400:
                    continue
                e = librosa.effects.preemphasis(seg)
                env = np.array([np.sum(e[i:i + 32] ** 2) for i in range(0, len(e) - 32, 16)]) + 1e-10
                r = 10 * np.log10(env[3:]) - 10 * np.log10(env[:-3])
                i0 = (np.argmax(r) + 3) * 16
                x = seg[max(0, i0 - 16):i0 + int(0.025 * SR)]
                if len(x) >= int(0.02 * SR):
                    toks[p['phone']].append((float(np.max(r)), x))
    data = {}
    for p, ts in toks.items():
        if not ts:
            continue
        if p in FRIC:
            ts.sort(key=lambda t: -t[0])
            parts, n, fade = [], 0, int(0.005 * SR)
            for _, x in ts:
                if p in VOICED_FRIC or not hpv:
                    x = sg.sosfiltfilt(hps if p in SIBILANT else hp, x)
                else:
                    x = x - x.mean()
                x = x / (np.sqrt(np.mean(x ** 2)) + 1e-9)
                parts.append(x)
                n += len(x)
                if n >= ms * SR / 1000:
                    break
            y = parts[0]
            for x in parts[1:]:
                w = np.linspace(0, 1, fade)
                y = np.concatenate([y[:-fade], y[-fade:] * (1 - w) + x[:fade] * w, x[fade:]])
            y = y[:int(ms * SR / 1000)]
        else:
            # the release closest to the median spectrum of the strongest half
            ts.sort(key=lambda t: -t[0])
            best = ts[:max(1, len(ts) // 2)]
            specs = [np.log(np.abs(np.fft.rfft(x[:400] * np.hanning(min(400, len(x))), 512)) + 1e-6) for _, x in best]
            med = np.median(specs, axis=0)
            y = best[int(np.argmin([np.sum((s - med) ** 2) for s in specs]))][1]
            y = y - y.mean()
            y = y * np.hanning(2 * len(y))[len(y):] ** 0.5  # fade out
        y = y / (np.max(np.abs(y)) + 1e-9) * 0.99
        rms = float(np.sqrt(np.mean(y ** 2)))
        data[p] = (base64.b64encode(mulaw(y).tobytes()).decode(), rms, len(ts))
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/**\n * Recorded consonant noise for the Strudel voice instrument (generated by\n'
                ' * scripts/speech/corpus/extract-consonant-noise.py; do not edit). Snippets of turbulence and\n'
                ' * stop releases from the CMU ARCTIC awb recordings (Copyright Carnegie Mellon University, free to\n'
                ' * use and modify with attribution), 16 kHz mu-law, base64. rms: of the decoded snippet, for level\n'
                ' * matching; n: tokens available.\n */\n')
        f.write('export const NOISE_RATE = 16000\n\n')
        f.write('export const CONSONANT_NOISE: Record<string, { data: string; rms: number; n: number }> = {\n')
        for p, (b, rms, n) in data.items():
            f.write(f"  '{p}': {{ rms: {rms:.4f}, n: {n}, data: '{b}' }},\n")
        f.write('}\n')
    print({p: (len(base64.b64decode(b)), round(r, 3), n) for p, (b, r, n) in data.items()})


if __name__ == '__main__':
    main()
